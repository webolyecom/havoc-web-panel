CREATE TABLE usage_accounts(
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  disk_bytes INTEGER NOT NULL DEFAULT 0, db_bytes INTEGER NOT NULL DEFAULT 0, inodes INTEGER NOT NULL DEFAULT 0, bw_month INTEGER NOT NULL DEFAULT 0,
  state TEXT NOT NULL DEFAULT 'ok', ratios TEXT, updated_at TEXT
);
CREATE TABLE traffic_daily(
  domain_id INTEGER NOT NULL REFERENCES domains(id) ON DELETE CASCADE, day TEXT NOT NULL,
  bytes INTEGER NOT NULL DEFAULT 0, hits INTEGER NOT NULL DEFAULT 0, s2 INTEGER NOT NULL DEFAULT 0, s3 INTEGER NOT NULL DEFAULT 0, s4 INTEGER NOT NULL DEFAULT 0, s5 INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(domain_id, day)
);
CREATE TABLE traffic_state(domain_id INTEGER PRIMARY KEY REFERENCES domains(id) ON DELETE CASCADE, pos INTEGER NOT NULL DEFAULT 0);
ALTER TABLE domains ADD COLUMN quota_suspended INTEGER NOT NULL DEFAULT 0;
