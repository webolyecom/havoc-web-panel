CREATE TABLE users(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  parent_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK(role IN('admin','reseller','user')),
  username TEXT NOT NULL UNIQUE COLLATE NOCASE,
  email TEXT NOT NULL,
  password TEXT NOT NULL,
  totp_secret TEXT,
  totp_enabled INTEGER NOT NULL DEFAULT 0,
  locale TEXT NOT NULL DEFAULT 'en',
  theme TEXT NOT NULL DEFAULT 'system',
  package_id INTEGER REFERENCES packages(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK(status IN('active','suspended')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE packages(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  disk_mb INTEGER NOT NULL DEFAULT 5120, bandwidth_mb INTEGER NOT NULL DEFAULT 102400,
  inodes INTEGER NOT NULL DEFAULT 250000, cpu_percent INTEGER NOT NULL DEFAULT 100,
  ram_mb INTEGER NOT NULL DEFAULT 1024, max_domains INTEGER NOT NULL DEFAULT 5,
  max_databases INTEGER NOT NULL DEFAULT 5, max_ftp INTEGER NOT NULL DEFAULT 5, max_cron INTEGER NOT NULL DEFAULT 10
);
CREATE TABLE domains(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  parent_id INTEGER REFERENCES domains(id) ON DELETE CASCADE,
  name TEXT NOT NULL UNIQUE COLLATE NOCASE,
  type TEXT NOT NULL DEFAULT 'main' CHECK(type IN('main','sub','alias','addon')),
  docroot TEXT,
  php_version TEXT NOT NULL DEFAULT '8.2',
  php_extensions TEXT,
  opcache_enabled INTEGER NOT NULL DEFAULT 1,
  opcache_memory INTEGER NOT NULL DEFAULT 128,
  ssl_mode TEXT NOT NULL DEFAULT 'none' CHECK(ssl_mode IN('none','letsencrypt','cloudflare','custom')),
  force_https INTEGER NOT NULL DEFAULT 0,
  hsts INTEGER NOT NULL DEFAULT 0,
  waf INTEGER NOT NULL DEFAULT 0,
  logs_enabled INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE api_tokens(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL, token_hash TEXT NOT NULL UNIQUE, last_used TEXT,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE audit_log(
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, username TEXT, ip TEXT,
  action TEXT NOT NULL, target TEXT, meta TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE login_attempts(id INTEGER PRIMARY KEY AUTOINCREMENT, ip TEXT NOT NULL, username TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE INDEX idx_login_attempts ON login_attempts(ip, username, ts);
CREATE TABLE branding(
  reseller_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  brand_name TEXT, logo_path TEXT, primary_color TEXT, panel_domain TEXT UNIQUE
);
CREATE TABLE db_instances(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, name TEXT NOT NULL UNIQUE, db_user TEXT NOT NULL, remote_access INTEGER NOT NULL DEFAULT 0);
CREATE TABLE ftp_accounts(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, login TEXT NOT NULL UNIQUE, home TEXT NOT NULL, quota_mb INTEGER NOT NULL DEFAULT 0, sftp_only INTEGER NOT NULL DEFAULT 0);
CREATE TABLE cron_jobs(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, domain_id INTEGER REFERENCES domains(id) ON DELETE CASCADE, schedule TEXT NOT NULL, command TEXT NOT NULL, enabled INTEGER NOT NULL DEFAULT 1);
CREATE TABLE dns_records(id INTEGER PRIMARY KEY AUTOINCREMENT, domain_id INTEGER NOT NULL REFERENCES domains(id) ON DELETE CASCADE, type TEXT NOT NULL, name TEXT NOT NULL, content TEXT NOT NULL, ttl INTEGER NOT NULL DEFAULT 3600, prio INTEGER);
CREATE TABLE redirects(id INTEGER PRIMARY KEY AUTOINCREMENT, domain_id INTEGER NOT NULL REFERENCES domains(id) ON DELETE CASCADE, source TEXT NOT NULL, target TEXT NOT NULL, code INTEGER NOT NULL DEFAULT 301);
CREATE TABLE backup_targets(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, type TEXT NOT NULL CHECK(type IN('local','s3','ftp','sftp')), config_enc TEXT);
CREATE TABLE backups(id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, domain_id INTEGER REFERENCES domains(id) ON DELETE SET NULL, target_id INTEGER REFERENCES backup_targets(id) ON DELETE SET NULL, path TEXT, size INTEGER, schedule TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
